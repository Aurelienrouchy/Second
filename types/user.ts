/**
 * Genre choisi à l'onboarding (rayon de prédilection).
 * Écrit dans la map `preferences` par la callable d'onboarding.
 */
export type Sex = 'femme' | 'homme' | 'les-deux' | 'enfant';

export interface UserPreferences {
  sizes: string[];
  /** Système utilisé pour afficher et interpréter les tailles. */
  sizeSystem?: 'EU' | 'US';
  /**
   * Pointures (tailles de chaussures), écrites dans la map `preferences`
   * par la callable d'onboarding, séparément de `sizes` (tailles vêtements).
   */
  shoesSizes?: string[];
  /**
   * Genre choisi à l'onboarding, écrit dans la map `preferences`
   * par la callable d'onboarding.
   */
  sex?: Sex;
  favoriteBrands: string[];
  location?: {
    latitude: number;
    longitude: number;
    city: string;
  };
  shippingCarriers?: string[];
  notifications?: {
    email: boolean;
    push: boolean;
    newMessages: boolean;
    newOrders: boolean;
    priceDrops: boolean;
    articleFavorited: boolean;    // Quand quelqu'un ajoute mon article en favori
    swapZoneReminder: boolean;    // Rappel 3 jours avant une swap zone
    offerReceived: boolean;       // Nouvelle proposition d'achat
    offerResponse: boolean;       // Réponse à ma proposition
  };
  privacy?: {
    /**
     * Privacy-by-default (Loi 25 art. 9.1) : la photo de profil n'est PAS visible
     * publiquement tant que l'utilisateur ne l'a pas explicitement activé.
     * ABSENT => false (privacy by default). Default = false pour les NOUVEAUX
     * utilisateurs ; les préférences déjà enregistrées ne sont jamais réécrites.
     */
    showProfilePhoto: boolean;
    /** @deprecated Not implemented — toggle removed from UI */
    allowSearchEngines?: boolean;
  };
  /**
   * Opt-in flag for AI personalisation/profiling (style profile, recommendations).
   * ABSENT or false => AI profiling DISABLED (explicit opt-in, Loi 25 / RGPD).
   * Default = false. Managed via the user preferences flow, NOT recordSignupConsent.
   */
  aiProfilingConsent?: boolean;
  /**
   * Consentement aux communications marketing (LCAP / Loi canadienne anti-pourriel).
   * Le consentement INITIAL (opt-in) est enregistré côté serveur dans la sous-collection
   * users/{uid}/consents (type 'marketing', version POLICY_VERSION) via recordSignupConsent.
   * Ce champ est le miroir applicatif de l'état courant : passer à `false` matérialise un
   * RETRAIT du consentement (art. 14), retirable et réactivable à tout moment depuis
   * app/settings/privacy.tsx. ABSENT => pas de consentement marketing actif (privacy by default).
   */
  marketingConsent?: boolean;
  /**
   * Consentement aux statistiques d'usage anonymisées (analytics produit).
   * Modèle OPT-OUT (Loi 25) : activé par défaut, aucune donnée personnelle
   * collectée. ABSENT => activé (true). Retirable/réactivable à tout moment
   * depuis app/settings/privacy.tsx (câblé sur lib/analytics#setAnalyticsEnabled).
   */
  analyticsConsent?: boolean;
}

/**
 * AI-generated style profile from user behavior
 * Generated by Gemini after signup with guest data
 */
export interface StyleProfile {
  styleTags: string[];                // ["Streetwear", "Vintage", "Casual"]
  styleDescription: string;           // Description naturelle du style en français
  recommendedBrands: string[];        // Marques suggérées
  suggestedSizes: { top: string; bottom: string };
  confidence: number;                 // 0-1 score de confiance
  generatedAt: Date;
}

export interface User {
  id: string;
  email: string;
  displayName?: string;
  /**
   * Persistent, unique, immutable @handle (e.g. "marie.dupont"). Derived once
   * from displayName at account creation and assigned EXCLUSIVELY server-side by
   * the assignUsername callable (Admin SDK). Never chosen or editable by the
   * user; decoupled from displayName (which stays freely editable). Optional to
   * tolerate the brief transient state before assignment completes.
   */
  username?: string;
  bio?: string;
  profileImage?: string;
  /** ISO "YYYY-MM-DD" — stored as a string (no Date/object) to avoid timezone drift. Set server-side via recordSignupConsent. */
  dateOfBirth?: string;
  createdAt: Date;
  rating?: number;
  phoneNumber?: string;
  address?: {
    street: string;
    city: string;
    province?: string;
    postalCode: string;
    country: string;
  };
  isActive?: boolean;
  accountType?: 'user' | 'shop';
  isAdmin?: boolean;
  preferences?: UserPreferences;
  styleProfile?: StyleProfile;
  onboardingCompleted?: boolean;
  authProvider?: 'email' | 'google' | 'apple';
  fcmTokens?: string[];  // Firebase Cloud Messaging tokens for push notifications
  likedSellers?: string[];     // IDs des vendeurs aimés
  sellerLikesCount?: number;   // Nombre de likes reçus en tant que vendeur
  articlesCount?: number;      // Nombre d'articles actifs
  salesCount?: number;         // Nombre de ventes réalisées
  // Stripe Connect
  stripeAccountId?: string;
  stripeAccountStatus?: string;
  stripeChargesEnabled?: boolean;
  stripePayoutsEnabled?: boolean;
  stripeDetailsSubmitted?: boolean;
  stripeRequirementsCurrentlyDue?: string[];
  stripeRequirementsPastDue?: string[];
  stripeRequirementsDisabledReason?: string | null;
  stripeBankAccountAdded?: boolean;
  stripeBankAccountLast4?: string;
  stripeBankAccountStatus?: string;
}
